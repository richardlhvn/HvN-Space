import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.TEST_URL || 'http://localhost:8080';
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox']});
const context = await browser.newContext({viewport: {width:1440, height:1050}});
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
const route = path => new URL(path, base).href;
await fs.mkdir('test-results', {recursive:true});
try {
  let response = await page.goto(base);
  check(response.status() === 200, 'Homepage responds successfully');
  await page.evaluate(() => document.fonts.ready);
  check(await page.locator('.hero h1').textContent().then(t => t.includes('stay')), 'Homepage hero rendered');
  check(await page.locator('.music-card').count() === 4, 'Featured artists rendered');
  await page.screenshot({path:'test-results/home-desktop.png', fullPage:true});
  await page.locator('.music-card').first().locator('[data-save]').click();
  check(await page.locator('.saved-count').textContent() === '1', 'Saving updates count');
  await page.reload();
  check(await page.locator('.music-card').first().locator('[data-save]').getAttribute('aria-pressed') === 'true', 'Save persists after reload');
  await page.goto(route('/saved/'));
  await page.waitForSelector('#saved-items .music-card');
  check(await page.locator('#saved-items .music-card').count() === 1, 'Saved collection loads');
  await page.locator('#saved-items [data-save]').click();
  await page.waitForSelector('#saved-empty:not([hidden])');
  check(await page.locator('#saved-empty').isVisible(), 'Removing last save restores empty state');
  await page.goto(route('/artists/'));
  const artistTotal = Number((await page.locator('.results-heading').textContent()).match(/\d+/)[0]);
  check(artistTotal >= 6 && await page.locator('.music-card').count() === Math.min(12, artistTotal), 'Artist directory renders its reported result count');
  await page.getByLabel('Search this directory').fill('Sara Kays');
  await page.locator('.filter-bar button[type=submit]').click();
  check(await page.locator('.music-card').count() === 1, 'Artist name filter works');
  check(await page.locator('.music-card h3').textContent() === 'Sara Kays', 'Correct artist returned');
  await page.selectOption('#filter-mood', 'hopeful');
  await page.locator('.filter-bar button[type=submit]').click();
  check(await page.locator('.empty-state').isVisible(), 'Combined filters use AND');
  await page.locator('.empty-state .button').click();
  const moods = await page.request.get(route('/wp-json/wp/v2/mood?slug=reflective'));
  const reflective = (await moods.json())[0];
  const expectedArtists = await page.request.get(route(`/wp-json/wp/v2/artist?mood=${reflective.id}&per_page=1`));
  const moodTotal = Number(expectedArtists.headers()['x-wp-total']);
  await page.selectOption('#filter-mood', 'reflective');
  await page.locator('.filter-bar button[type=submit]').click();
  check(moodTotal > 0 && await page.locator('.music-card').count() === Math.min(12, moodTotal), 'Mood filter matches the independently queried catalog');
  await page.goto(route('/artists/?q=BL%C3%9C%20EYES'));
  check(await page.locator('.music-card').count() === 1 && await page.locator('.music-card h3').textContent() === 'BLÜ EYES', 'Unicode artist-name filtering preserves display names');
  await page.goto(route('/artists/?filter_country=germany'));
  check(await page.locator('.music-card').count() === 1 && await page.locator('.music-card h3').textContent() === 'Hanniou', 'Country filter finds the sourced German artist');
  await page.goto(route('/artists/sara-kays/'));
  check(await page.locator('h1').textContent() === 'Sara Kays', 'Artist profile renders');
  check(await page.locator('.editorial-notice').textContent().then(t => t.includes('demo collection') || t.includes('Research review pending')), 'Demo is labeled');
  check(await page.locator('meta[name=robots]').getAttribute('content').then(t => t.includes('noindex')), 'Demo has noindex');
  check(await page.locator('.related-grid .music-card').count() === 2, 'Curated artist relationships render');
  const spotifyLink = page.locator('.spotify-button');
  const spotifyHref = await spotifyLink.getAttribute('href');
  check(spotifyHref.startsWith('https://open.spotify.com/search/') ? (await spotifyLink.textContent()).includes('Find on Spotify') : /^https:\/\/open\.spotify\.com\/artist\/[A-Za-z0-9]{22}$/.test(spotifyHref) && (await spotifyLink.textContent()).includes('Open in Spotify'), 'Spotify link and its label match verified artist or search fallback');
  await page.screenshot({path:'test-results/artist-desktop.png', fullPage:true});
  await page.goto(route('/songs/'));
  const songTotal = Number((await page.locator('.results-heading').textContent()).match(/\d+/)[0]);
  check(songTotal >= 6 && await page.locator('.music-card').count() === Math.min(12, songTotal), 'Song directory renders its reported result count');
  await page.goto(route('/songs/coping/'));
  check(await page.locator('.meaning-label').textContent().then(t => t.includes('Afterglow interpretation')), 'Interpretation is labeled');
  const intentText = await page.locator('.profile-section').textContent();
  const attributed = await page.locator('.attribution-label').count();
  check(intentText.includes('No verified artist explanation') || (attributed === 1 && await page.locator('.source-list a').count() > 0), 'Artist commentary has attribution and sources, or missing intent is disclosed');
  check(await page.locator('.artist-byline').textContent().then(t => t.includes('Rosie Darling')), 'Song links its artist');
  await page.locator('.search-trigger').click();
  await page.locator('#global-search').fill('Sara Kays');
  await page.locator('#search-dialog button[type=submit]').click();
  check(await page.locator('.search-list h2').allTextContents().then(items => items.includes('Sara Kays')), 'Global search finds artists');
  await page.goto(route('/?s=zzznomatchzz'));
  check(await page.locator('.empty-state').isVisible(), 'Search has empty state');
  for (const path of ['/journal/', '/about/', '/privacy/', '/contact/', '/copyright/']) {
    response = await page.goto(route(path));
    check(response.status() === 200 && await page.locator('main h1').count() === 1, `${path} renders`);
  }
  response = await page.goto(route('/not-a-real-page/'));
  check(response.status() === 404 && await page.locator('h1').textContent().then(t => t.includes('quiet')), 'Missing pages send 404');
  response = await page.request.get(route('/wp-json/afterglow/v1/saved?ids=not-an-id'));
  check(response.ok() && JSON.stringify(await response.json()) === '[]', 'Saved endpoint handles invalid IDs');
  await page.setViewportSize({width:390, height:844});
  await page.goto(base);
  await page.evaluate(() => document.fonts.ready);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile homepage has no overflow');
  await page.screenshot({path:'test-results/home-mobile.png', fullPage:true});
  await page.locator('.mobile-menu').click();
  check(await page.locator('#primary-nav').isVisible(), 'Mobile navigation opens');
  await page.locator('#primary-nav').getByRole('link', {name:'Artists', exact:true}).click();
  check(await page.locator('h1').textContent().then(t => t.includes('voice')), 'Mobile navigation works');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile directory has no overflow');
  await page.goto(route('/artists/sara-kays/'));
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile artist has no overflow');
  await page.screenshot({path:'test-results/artist-mobile.png', fullPage:true});
  await page.locator('.search-trigger').click();
  check(await page.locator('#search-dialog').isVisible(), 'Mobile search opens');
  await page.keyboard.press('Escape');
  check(!await page.locator('#search-dialog').isVisible(), 'Search supports Escape');
  check(errors.length === 0, `No browser errors: ${errors.join(', ')}`);
  console.log(`PASS: ${checks} functional browser checks. Screenshots in test-results/.`);
} finally { await browser.close(); }
