#!/usr/bin/env python3
"""Build one public WP-CLI patch; includes no database or credentials."""
import base64
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
payload = {
    name: base64.b64encode((root / "theme" / name).read_bytes()).decode()
    for name in ["page-contact.php", "assets/contact.css"]
}
packed = base64.b64encode(json.dumps(payload).encode()).decode()
source = (root / "scripts/hosting/update-contact.php").read_text()
output = root / "downloads/tunetofond-contact-update.php"
output.write_text("<?php\n// Generated by scripts/package-contact-update.py.\n"
                  + "$tf_contact_release = json_decode(base64_decode('" + packed + "'), true);\n"
                  + source.removeprefix("<?php\n"))
print(output.relative_to(root))
